/**
 * Filter and search emojis by text query and category
 */
export function filterGoogleEmojis(
  query: string,
  category?: EmojiCategory | 'All'
): GoogleEmoji[] {
  const cleanQuery = query.trim().toLowerCase();

  return ALL_GOOGLE_EMOJIS.filter((item) => {
    // Category check
    if (category && category !== 'All' && item.category !== category) {
      return false;
    }

    if (!cleanQuery) return true;

    if (item.emoji.includes(cleanQuery)) return true;
    if (item.name.toLowerCase().includes(cleanQuery)) return true;
    return item.keywords.some((kw) => kw.toLowerCase().includes(cleanQuery));
  });
}
